#!/usr/bin/env python3
"""Write src/gl_core.inc: the names of ALL_GL_FUNCS in Wine's include/wine/wgl.h.

Those are the OpenGL 1.1 entry points opengl32.dll exports. Wine calls each through its function
table without a NULL check, so glmt gives every one of them an address: its own function where it
has one, a logging stub otherwise.

    tools/gen-core-names.py <wine>/include/wine/wgl.h > src/gl_core.inc
"""
import re
import sys


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    text = open(sys.argv[1], encoding="utf-8").read()
    block = re.search(r"#define ALL_GL_FUNCS \\\n((?:\s+USE_GL_FUNC\(\w+\)(?: \\)?\n)+)", text)
    if not block:
        print("ALL_GL_FUNCS not found", file=sys.stderr)
        return 1
    names = re.findall(r"USE_GL_FUNC\((\w+)\)", block.group(1))
    print("/* Generated by tools/gen-core-names.py from Wine's include/wine/wgl.h (ALL_GL_FUNCS).")
    print(f"   {len(names)} OpenGL 1.1 entry points. Do not edit. */")
    for name in names:
        print(f"GL_CORE({name})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
