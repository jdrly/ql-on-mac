#!/usr/bin/env python3
"""Print a text file as a C string constant.

    tools/embed.py <name> <file>  >  <file>.inc

gives `static const char <name>[] = "...";`, for a source the library carries inside itself (the
Metal shader source, which the backend hands to Metal's compiler at start).
"""
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    name, path = sys.argv[1], sys.argv[2]
    print(f"/* Generated by tools/embed.py from {path}. Do not edit. */")
    print(f"static const char {name}[] =")
    with open(path, encoding="utf-8") as source:
        for line in source:
            escaped = line.rstrip("\n").replace("\\", "\\\\").replace('"', '\\"')
            print(f'    "{escaped}\\n"')
    print("    ;")
    return 0


if __name__ == "__main__":
    sys.exit(main())
